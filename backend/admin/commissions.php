// Taka formatter: 480000 -> ৳ 4.8L, 25500 -> ৳ 25,500
function taka($n) {
  $n = (float)$n;
  if ($n >= 100000) {
    return '৳ ' . rtrim(rtrim(number_format($n / 100000, 1), '0'), '.') . 'L';
  }
  return '৳ ' . number_format($n);
}

// ---------- Summary cards ----------
$earned = $pending = $paid = 0;
$paidCount = 0;
$avgRate = 0;

$r = $conn->query("SELECT
    COALESCE(SUM(CASE WHEN c.created_at >= DATE_FORMAT(CURDATE(), '%Y-%m-01') THEN c.amount END), 0) AS earned,
    COALESCE(SUM(CASE WHEN c.payment_status = 'pending' THEN c.amount END), 0) AS pending,
    COALESCE(SUM(CASE WHEN c.payment_status = 'paid' AND c.paid_at >= DATE_FORMAT(CURDATE(), '%Y-%m-01') THEN c.amount END), 0) AS paid,
    SUM(c.payment_status = 'paid' AND c.paid_at >= DATE_FORMAT(CURDATE(), '%Y-%m-01')) AS paid_count,
    COALESCE(AVG(a.commission_rate), 0) AS avg_rate
  FROM commissions c
  LEFT JOIN agents a ON a.agent_id = c.agent_id");
if ($r && ($s = $r->fetch_assoc())) {
  $earned    = $s['earned'];
  $pending   = $s['pending'];
  $paid      = $s['paid'];
  $paidCount = (int)$s['paid_count'];
  $avgRate   = (float)$s['avg_rate'];
}

// ---------- Commission records ----------
$rows = [];
$res = $conn->query("SELECT c.commission_id, c.agent_id, c.agreement_id, c.amount, c.payment_status,
                            a.commission_rate
                     FROM commissions c
                     LEFT JOIN agents a ON a.agent_id = c.agent_id
                     ORDER BY c.created_at DESC
                     LIMIT 50");
while ($c = $res->fetch_assoc()) {
  $rows[] = [
    'id'          => 'COM-' . str_pad($c['commission_id'], 4, '0', STR_PAD_LEFT),
    'agent'       => 'Agent #' . (int)$c['agent_id'],
    'transaction' => 'Agreement #' . (int)$c['agreement_id'],
    'rate'        => $c['commission_rate'] !== null ? rtrim(rtrim(number_format($c['commission_rate'], 2), '0'), '.') . '%' : '—',
    'amount'      => taka($c['amount']),
    'status'      => ucfirst($c['payment_status']),
  ];
}

